//! Built-in macro definitions — full VERSIONED catalog.
//!
//! Contains the canonical list of all SugarCube 2 builtin macro definitions,
//! organized by category (Control flow, Variables, Output, DOM, Links, etc.).
//!
//! ## Versioning
//!
//! The catalog is the UNION of every macro that ever existed in SugarCube
//! 2.x — including deprecated and removed ones — each carrying:
//!
//! - `added_in`: first version the macro exists in (baseline 2.0.0 for
//!   macros predating finer-grained records);
//! - `deprecated_in` / `removed_in`: lifecycle boundaries;
//! - `descriptors`: per-era description/args, ascending by `since`. The
//!   effective descriptor at a story's version is the last one whose
//!   `since <= version` — this is how the same macro can be described
//!   differently in different SugarCube versions.
//!
//! The raw list must NOT be used for user-facing features (completions,
//! hover, diagnostics) — those go through [`macros_at`] / `descriptor_at`
//! / `status_at` so only macros relevant to the story's pinned
//! `format-version` are surfaced. Structural parsing (tree building,
//! pairing) may use the version-blind lookups: removed macros must still
//! parse syntactically while being flagged.
//!
//! Version data sources: SugarCube v2 docs per-macro History sections,
//! the docs upgrade guides (≥2.37.0 … ≥2.8.0), release notes 2.31.0–2.37.3,
//! and the 2.37.3 engine source (Macro.add scan).

